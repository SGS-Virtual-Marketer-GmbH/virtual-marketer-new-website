#!/usr/bin/env node

/**
 * German Contact Page (/kontakt/)
 *
 * The only "contact" mechanism on the site used to be scattered mailto:
 * links — no page anywhere used backend/'s working POST /api/contact
 * endpoint (see backend/README.md for the request/response contract:
 * {name, email, message, locale} -> 201/400/429, confirmation via an
 * emailed link, not a code). This script builds the missing DE page,
 * mounting the assets/contact-form/ widget (same architecture as
 * assets/booking-widget/: vanilla JS, data-locale attribute, brand colors
 * via CSS custom properties, fetch() straight to /api/contact).
 *
 * This is a small, dedicated generator rather than folding into
 * generate-feature-pages.js or generate-blog-posts.js: this is the first
 * non-blog, non-feature, self-generated DE page, so it gets its own script
 * following the exact same header()/footer()/pageShell()/write() shape
 * those scripts already use (copied here, not imported — neither script
 * exports these helpers).
 *
 * The EN counterpart (/en/contact/) is generated by generate-en-pages.js.
 * This page pair is registered in inject-language-switcher.js's DE_TO_EN
 * map and generate-en-pages.js's EN_TO_DE map for hreflang/switcher wiring
 * — see those files' header comments for why naive path-stripping for
 * hreflang was a bug fixed in this project (slugs diverge DE/EN).
 *
 * Run after scripts/build.js (so the theme CSS this page reuses already
 * exists in dist/) and before scripts/inject-language-switcher.js /
 * scripts/fix-navigation.js (so those post-build passes can find and patch
 * this page too).
 */

const fs = require('fs');
const path = require('path');
const { CHROME_CSS } = require('./lib/page-chrome');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const BASE_URL = 'https://virtual-marketer.de';
const LOGO = '/wp-content/uploads/2023/04/cropped-Virtual-Marketer-Logo-128x128-New.png';

function resolveThemeAsset(cleanRelPath) {
  const dir = path.dirname(path.join(DIST, cleanRelPath));
  const base = path.basename(cleanRelPath);
  if (!fs.existsSync(dir)) return cleanRelPath;
  const match = fs.readdirSync(dir).find((f) => f === base || f.startsWith(`${base}?`));
  const resolved = match ? path.join(path.dirname(cleanRelPath), match) : cleanRelPath;
  return resolved.replace(/\?/g, '%3F');
}

const THEME_CSS = {
  bootstrap: resolveThemeAsset('wp-content/themes/engitech/css/bootstrap.css'),
  fontAwesome: resolveThemeAsset('wp-content/themes/engitech/css/font-awesome.min.css'),
  style: resolveThemeAsset('wp-content/themes/engitech/style.css'),
};

function header() {
  return `<header class="vm-header-simple">
  <a href="/"><img src="${LOGO}" alt="Virtual Marketer" style="height:40px;width:auto;max-width:none"></a>
  <nav>
    <a href="/ki-loesungen/">Lösungen</a>
    <a href="/blog/">Blog</a>
    <a href="https://api.virtual-marketer.de/documentation/">API</a>
    <a href="/modell-anfragen/">Modell anfragen</a>
    <a href="/kontakt/">Kontakt</a>
    <a href="https://login.virtual-marketer.de/">Login</a>
  </nav>
</header>`;
}

function footer() {
  return `<footer style="max-width:1140px;margin:64px auto 0;padding:24px 20px;border-top:1px solid #e5e7eb;color:#6b7280;font-size:14px;">
  &copy; 2026 SGS Virtual Marketer GmbH &middot;
  <a href="/datenschutzerklaerung/">Datenschutzerklärung</a> &middot;
  <a href="/impressum/">Impressum</a>
</footer>`;
}

const BASE_CSS = `
  :root{
    --vm-red:#94152b; --vm-red-dark:#700f2b; --vm-blue:#66a3ce; --vm-blue-light:#a3cce9;
    --vm-gray-100:#f4f1f1; --vm-gray-200:#e7dfe0; --vm-gray-500:#6b5f60; --vm-gray-900:#241417;
  }
  .vm-kontakt *{box-sizing:border-box;}
  .vm-kontakt{max-width:900px;margin:0 auto;padding:48px 20px 96px;color:var(--vm-gray-900);line-height:1.65;font-size:16px;}
  .vm-kontakt h1{font-size:36px;line-height:1.15;margin:0 0 12px;letter-spacing:-.01em;}
  .vm-kontakt p{margin:0 0 14px;color:#4a4143;}
  .vm-kontakt a{color:var(--vm-red);}
  .vm-kontakt .eyebrow{display:inline-block;font-size:12.5px;font-weight:700;letter-spacing:.06em;text-transform:uppercase;color:var(--vm-red);background:#fbecee;padding:5px 12px;border-radius:999px;margin-bottom:16px;}
  .vm-kontakt .lede{font-size:18px;color:#4a4143;max-width:62ch;}
`;

function pageShell({ titleTag, description, keywords, urlPath, bodyHtml, jsonLd, hreflangEn }) {
  const url = `${BASE_URL}${urlPath}`;
  return `<!doctype html>
<html lang="de">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${titleTag} | Virtual Marketer</title>
<meta name="description" content="${description}">
${keywords ? `<meta name="keywords" content="${keywords}">\n` : ''}<meta name="robots" content="index, follow">
<link rel="canonical" href="${url}">
<link rel="alternate" hreflang="de" href="${url}">
<link rel="alternate" hreflang="en" href="${BASE_URL}${hreflangEn}">
<link rel="alternate" hreflang="x-default" href="${url}">
<meta property="og:type" content="website">
<meta property="og:locale" content="de_DE">
<meta property="og:site_name" content="Virtual Marketer">
<meta property="og:title" content="${titleTag}">
<meta property="og:description" content="${description}">
<meta property="og:url" content="${url}">
<meta name="twitter:card" content="summary">
${jsonLd ? `<script type="application/ld+json">${JSON.stringify(jsonLd)}</script>\n` : ''}<link rel="stylesheet" href="/${THEME_CSS.bootstrap}">
<link rel="stylesheet" href="/${THEME_CSS.fontAwesome}">
<link rel="stylesheet" href="/${THEME_CSS.style}">
<style>${BASE_CSS}${CHROME_CSS}</style>
</head>
<body class="vm-static-blog">
${header()}
<main class="vm-kontakt">
${bodyHtml}
</main>
${footer()}
</body>
</html>`;
}

function write(urlPath, html) {
  const outDir = path.join(DIST, ...urlPath.split('/').filter(Boolean));
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), html);
}

function main() {
  console.log('\n✉️  Generating German contact page...\n');

  // Copy the contact-form widget assets into dist/ — same pattern as
  // scripts/inject-booking-widget.js copying assets/booking-widget/.
  const assetSrc = path.join(ROOT, 'assets/contact-form');
  const assetDist = path.join(DIST, 'assets/contact-form');
  fs.mkdirSync(assetDist, { recursive: true });
  fs.copyFileSync(path.join(assetSrc, 'contact-form.css'), path.join(assetDist, 'contact-form.css'));
  fs.copyFileSync(path.join(assetSrc, 'contact-form.js'), path.join(assetDist, 'contact-form.js'));
  console.log('  ✓ Copied contact-form.css / contact-form.js to dist/assets/contact-form/');

  write('/kontakt/', pageShell({
    titleTag: 'Kontakt',
    description: 'Kontaktieren Sie Virtual Marketer &#8211; schreiben Sie uns über das Kontaktformular oder direkt per E-Mail.',
    keywords: 'Kontakt, Virtual Marketer kontaktieren, KI Marketing Anfrage',
    urlPath: '/kontakt/',
    hreflangEn: '/en/contact/',
    jsonLd: {
      '@context': 'https://schema.org',
      '@type': 'ContactPage',
      name: 'Kontakt | Virtual Marketer',
      url: `${BASE_URL}/kontakt/`,
    },
    bodyHtml: `
<span class="eyebrow">Kontakt</span>
<h1>Kontaktieren Sie uns</h1>
<p class="lede">Haben Sie Fragen zu Virtual Marketer oder möchten Sie mehr über unsere KI-Marketinglösungen erfahren? Schreiben Sie uns &#8211; wir melden uns zeitnah zurück.</p>
<div id="vm-contact-form" data-locale="de"></div>
<link rel="stylesheet" href="/assets/contact-form/contact-form.css">
<script src="/assets/contact-form/contact-form.js" defer></script>
<p>Oder erreichen Sie uns direkt unter <a href="mailto:info@virtual-marketer.de">info@virtual-marketer.de</a>.</p>`,
  }));

  console.log('  ✓ /kontakt/');
  console.log('\n✅ German contact page generated\n');
}

main();
