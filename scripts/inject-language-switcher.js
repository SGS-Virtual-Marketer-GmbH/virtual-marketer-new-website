#!/usr/bin/env node

/**
 * Language Switcher Injector
 *
 * Adds a small, fixed-position "DE | EN" badge linking a German page to
 * its real English counterpart under /en/ on this same domain, and vice
 * versa. Only pages with an actual, built EN equivalent get the switcher
 * — for everything else (the ~90 legacy blog posts, tag/category/author
 * archives, etc.) injecting a switcher would just link to a 404, so those
 * pages are left alone entirely rather than showing a broken control.
 *
 * Note this is a real, same-domain /en/ path prefix, not the
 * virtual-marketer.ai domain referenced in earlier versions of this
 * project's hreflang comments — that domain was never registered/DNS
 * configured, so pointing users at it would be a dead link. See the
 * architecture note at the top of scripts/generate-feature-pages.js.
 *
 * Deliberately NOT wired into the existing Elementor header nav: that
 * markup is deeply nested, varies between pages, and generated by a page
 * builder rather than hand-written — regex-editing it reliably across all
 * ~74 pages is much higher-risk than adding one small, self-contained,
 * fixed-position element via the same safe end-of-body injection pattern
 * already used by scripts/inject-ai-features.js (lastIndexOf('</body>'),
 * not the first-match .replace() bug fixed there).
 *
 * Run after scripts/generate-en-pages.js and scripts/generate-feature-pages.js
 * (so every EN counterpart already exists), before scripts/seo-optimize.js.
 */

const fs = require('fs');
const path = require('path');

const DIST = path.join(__dirname, '../dist');

// Explicit DE -> EN path map — only pages that actually exist on both
// sides. Kept as one flat list (not derived from FEATURES) since this
// script has no reason to depend on generate-feature-pages.js's internals.
const DE_TO_EN = {
  '/': '/en/',
  '/ki-loesungen/': '/en/solutions/',
  '/ki-loesungen/agenten/': '/en/solutions/ai-agents/',
  '/ki-loesungen/coding-api/': '/en/solutions/coding-api/',
  '/ki-loesungen/produktfotos-ki/': '/en/solutions/ai-product-photos/',
  '/ki-loesungen/feed-veredelung/': '/en/solutions/feed-enhance/',
  '/ki-loesungen/texte-generieren/': '/en/solutions/ai-text-generator/',
  '/ki-loesungen/bilder-generieren/': '/en/solutions/ai-image-generator/',
  '/ki-loesungen/videos-generieren/': '/en/solutions/ai-video-generator/',
  '/ki-loesungen/seo-content/': '/en/solutions/ai-seo-content/',
  '/ki-loesungen/kampagnen-builder/': '/en/solutions/campaign-builder/',
  '/ki-loesungen/interne-verlinkung/': '/en/solutions/internal-linking/',
  '/ki-loesungen/mail-generator/': '/en/solutions/ai-email-generator/',
  '/impressum/': '/en/legal-notice/',
  '/datenschutzerklaerung/': '/en/privacy-policy/',
  '/nutzungsbedingungen/': '/en/terms-of-service/',
  '/faqs/': '/en/faqs/',
  '/management/': '/en/about/',
  '/modell-anfragen/': '/en/request-custom-model/',
  '/virtual-marketer-demo/': '/en/demo/',
  '/kontakt/': '/en/contact/',
};
const EN_TO_DE = Object.fromEntries(Object.entries(DE_TO_EN).map(([de, en]) => [en, de]));

const START_MARKER = '<!-- vm-lang-switch:start -->';
const END_MARKER = '<!-- vm-lang-switch:end -->';

function widget(dePath, enPath, isEn) {
  return `${START_MARKER}
<style>
  #vm-lang-switch{position:fixed;top:16px;right:16px;z-index:99998;display:flex;align-items:center;gap:6px;background:#ffffffee;backdrop-filter:blur(6px);border:1px solid #e5e7eb;border-radius:999px;padding:6px 10px;font:600 13px/1 -apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;box-shadow:0 2px 8px rgba(0,0,0,.08)}
  #vm-lang-switch a{color:#6b7280;text-decoration:none;padding:2px 6px;border-radius:999px}
  #vm-lang-switch a.active{color:#fff;background:#1a202c}
  @media (max-width:640px){#vm-lang-switch{top:auto;bottom:16px;right:16px}}
</style>
<div id="vm-lang-switch" role="navigation" aria-label="Sprache wählen / Language">
  <a href="${dePath}" class="${isEn ? '' : 'active'}" lang="de" hreflang="de">DE</a>
  <a href="${enPath}" class="${isEn ? 'active' : ''}" lang="en" hreflang="en">EN</a>
</div>
${END_MARKER}`;
}

function findHtmlFiles(dir, results = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) findHtmlFiles(full, results);
    else if (entry.name === 'index.html') results.push(full);
  }
  return results;
}

function main() {
  console.log('\n🌐 Injecting language switcher (DE ⇄ EN, real pages only)...\n');

  const files = findHtmlFiles(DIST);
  let injected = 0;
  let skipped = 0;

  for (const file of files) {
    const pagePath = '/' + path.relative(DIST, path.dirname(file)).split(path.sep).join('/') + (path.dirname(file) === DIST ? '' : '/');
    const cleanPath = pagePath === '//' ? '/' : pagePath;

    const isEn = cleanPath.startsWith('/en/') || cleanPath === '/en';
    const dePath = isEn ? EN_TO_DE[cleanPath] : cleanPath;
    const enPath = isEn ? cleanPath : DE_TO_EN[cleanPath];

    if (!dePath || !enPath) { skipped++; continue; } // no real counterpart — don't link to a 404

    let html = fs.readFileSync(file, 'utf-8');
    const section = widget(dePath, enPath, isEn);
    const startIdx = html.indexOf(START_MARKER);
    const endIdx = html.indexOf(END_MARKER);

    if (startIdx !== -1 && endIdx !== -1) {
      html = html.slice(0, startIdx) + section + html.slice(endIdx + END_MARKER.length);
    } else {
      const bodyCloseIdx = html.lastIndexOf('</body>');
      if (bodyCloseIdx === -1) { skipped++; continue; }
      html = html.slice(0, bodyCloseIdx) + section + '\n' + html.slice(bodyCloseIdx);
    }

    fs.writeFileSync(file, html);
    injected++;
  }

  console.log(`✅ Language switcher added to ${injected} page(s) with a real counterpart (${skipped} page(s) skipped — no EN/DE equivalent exists)\n`);
}

main();
